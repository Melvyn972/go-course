package repl

// Text pictures for the Windows console. Plain ASCII, narrow enough for 80 columns.

func sceneArt(id string) string {
	if s, ok := scenes[id]; ok {
		return s
	}
	return ""
}

func foeArt(slug string) string {
	if s, ok := foes[slug]; ok {
		return s
	}
	return ""
}

func houseArt(id string) string {
	if s, ok := houses[id]; ok {
		return s
	}
	return ""
}

func wandArt(id string) string {
	if s, ok := wands[id]; ok {
		return s
	}
	return ""
}

func spellArt(id string) string {
	if s, ok := spells[id]; ok {
		return s
	}
	return ""
}

